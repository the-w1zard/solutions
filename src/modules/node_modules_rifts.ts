export class NODE_MODULE_RIFTS {
	public root: A
	constructor(root: A = null) { this.root = root }
	public FULFIL_THIS_NOW(r: A) { this.root = r }
	public REFRESH_ROOT() { return this.root.acquire_root('NODE_MODULE_RIFTS') }

	public static loaded = new Map<string, A>();
	private static moduleExports = new Map<string, Map<string, A>>();
	private static blindRequire = new Function('specifier', 'return require(specifier)');

	public isLoaded(specifier: string): boolean { return NODE_MODULE_RIFTS.loaded.has(specifier); }
	public get modules(): ReadonlyMap<string, A> { return NODE_MODULE_RIFTS.loaded; }
	public getLoaded<T = A>(specifier: string): T | undefined { return NODE_MODULE_RIFTS.loaded.get(specifier) as T | undefined; }

	private indexExports(key: string, mod: A): void {
		if (!mod || (typeof mod !== 'object' && typeof mod !== 'function')) return;
		for (const name of Object.keys(mod)) {
			let sources = NODE_MODULE_RIFTS.moduleExports.get(name);
			if (!sources) { sources = new Map<string, A>(); NODE_MODULE_RIFTS.moduleExports.set(name, sources); }
			sources.set(key, mod[name]);
		}
	}
	public export<T = A>(name: string, specifier?: string): T | undefined {
		if (specifier !== undefined) return this.getLoaded<A>(specifier)?.[name] as T | undefined;
		const sources = NODE_MODULE_RIFTS.moduleExports.get(name);
		if (!sources || sources.size === 0) return undefined;
		if (sources.size > 1) throw new Error(`Ambiguous export "${name}" found in: ${[...sources.keys()].join(', ')}`);
		return sources.values().next().value as T | undefined;
	}
	public import<T = A>(specifier: string): T { return this.load<T>(specifier);	}
	public importAll<T = A>(specifier: string): T { return this.load<T>(specifier);	}
	public importNamed<T = A>(specifier: string, name: string): T | undefined { return this.export<T>(name, specifier);	}
	public load<T = A>(specifier: string): T {
		if (NODE_MODULE_RIFTS.loaded.has(specifier)) return NODE_MODULE_RIFTS.loaded.get(specifier) as T;
		const mod = NODE_MODULE_RIFTS.blindRequire(specifier) as T;
		NODE_MODULE_RIFTS.loaded.set(specifier, mod as A);
		this.indexExports(specifier, mod as A);
		return mod;
	}

}
export const node_module_rifts = new NODE_MODULE_RIFTS()
